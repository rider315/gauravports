/* ==========================================================================
   Writes assets/js/contentful-config.js from the environment at build time, so
   the CMS credentials never sit in the repository. Vercel runs this through
   `npm run build` (see vercel.json); locally, put the values in a .env file and
   run `npm run build` yourself.

     CONTENTFUL_SPACE_ID      required
     CONTENTFUL_ACCESS_TOKEN  required — the Content Delivery (read-only) token
     CONTENTFUL_ENVIRONMENT   optional, defaults to "master"

   The generated file is git-ignored. The delivery token is read-only and is
   meant to be public, which is what makes a browser-side CMS fetch safe here.
   ========================================================================== */

const fs = require("fs");
const path = require("path");

/* A .env in the project root, for local builds. Vercel injects real env vars. */
function loadDotEnv() {
  const file = path.join(__dirname, ".env");
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (!match) continue;
    const value = match[2].trim().replace(/^["']|["']$/g, "");
    if (!(match[1] in process.env)) process.env[match[1]] = value;
  }
}

loadDotEnv();

const space = process.env.CONTENTFUL_SPACE_ID || "";
const token = process.env.CONTENTFUL_ACCESS_TOKEN || "";
const environment = process.env.CONTENTFUL_ENVIRONMENT || "master";

/* Nothing may end up inside the generated string literals. */
const quote = (value) => JSON.stringify(String(value));

const config = `// Generated by generate-config.js at build time — do not edit, do not commit.
window.CONTENTFUL_CONFIG = {
  SPACE_ID: ${quote(space)},
  ACCESS_TOKEN: ${quote(token)},
  ENVIRONMENT: ${quote(environment)}
};
`;

const dir = path.join(__dirname, "assets", "js");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "contentful-config.js"), config);

if (!space || !token) {
  /* A warning, not a failed build: the rest of the site must still deploy.
     The blog degrades to a "posts aren't available" note when this happens. */
  console.warn("⚠️  Contentful config is EMPTY — the blog will show no posts.");
  console.warn("    Missing:", [!space && "CONTENTFUL_SPACE_ID", !token && "CONTENTFUL_ACCESS_TOKEN"].filter(Boolean).join(", "));
  console.warn("    Set them in Vercel → Project → Settings → Environment Variables, then redeploy.");
} else {
  console.log(`✅ Contentful config written for space ${space} (environment: ${environment}).`);
}
